function parseLevels(layouts) {
  const STEP = 14;
  const BORDER_OFFSET = 0; // 2 steps * 14px

  return layouts.map((grid, levelIndex) => {
    const walls = [];
    grid.forEach((row, rIndex) => {
      row.forEach((cell, cIndex) => {
        if (cell === 1) {
          walls.push({
            x: cIndex * STEP + BORDER_OFFSET,
            y: rIndex * STEP + BORDER_OFFSET
          });
        }
      });
    });

    const num = levelIndex + 1;
    return {
      id: `level${num}`,
      dropdownName: `Level ${num}`,
      fullName: levelNames[levelIndex],
      walls: walls
    };
  });
}

export const NIBBLES_LEVELS = parseLevels(rawGrids);